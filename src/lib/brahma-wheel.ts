export function calculateBrahmaHouse(age: number, gender: "male" | "female"): BrahmaHouse {
  // Age must be positive
  const safeAge = Math.max(1, Math.floor(age));

  let houseNumber: number;
  if (gender === "male") {
    // Man: starts at House 1 (Chedi) and counts clockwise (1, 2, 3... 12)
    houseNumber = ((safeAge - 1) % 12) + 1;
  } else {
    // Woman: starts at House 1 (Chedi) and counts counter-clockwise (1, 12, 11... 2)
    if (safeAge === 1) {
      houseNumber = 1;
    } else {
      houseNumber = 12 - ((safeAge - 2) % 12);
    }
  }

  return BRAHMA_HOUSES[houseNumber] || BRAHMA_HOUSES[1];
}
