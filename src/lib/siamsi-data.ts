export function drawRandomSiamsi(): SiamsiFortune {
  const index = Math.floor(Math.random() * SIAMSI_FORTUNES.length);
  return SIAMSI_FORTUNES[index];
}

export function getSiamsiByNumber(num: number): SiamsiFortune | undefined {
  return SIAMSI_FORTUNES.find((item) => item.number === num);
}
