export function calculateLifeGraph(birthDateStr: string): LifeGraphResult {
  const date = new Date(birthDateStr);
  const dayIndex = date.getDay(); // 0 (Sun) - 6 (Sat)
  const dayNum = dayIndex === 0 ? 1 : dayIndex + 1; // 1 (Sun) - 7 (Sat)
  const monthNum = date.getMonth() + 1; // 1 - 12
  const year = date.getFullYear();

  // ปีนักษัตรจีน/ไทย (ปี 1900 คือปีชวด)
  const zodiacIndex = (year - 4) % 12 >= 0 ? (year - 4) % 12 : (year - 4) % 12 + 12;
  const zodiacNum = zodiacIndex + 1; // 1 (ชวด) - 12 (กุน)

  const houses: LifeGraphHouse[] = HOUSE_DEFINITIONS.map((def, index) => {
    // ฐานวัน
    const baseDay = ((dayNum + index - 1) % 7) + 1;
    // ฐานเดือน
    const baseMonth = ((monthNum + index - 1) % 12) + 1;
    // ฐานปี
    const baseYear = ((zodiacNum + index - 1) % 12) + 1;

    const sum = baseDay + baseMonth + baseYear;
    // คำนวณเป็นคะแนน 1 - 12
    const score = ((sum - 1) % 12) + 1;

    let grade: LifeGraphHouse["grade"] = "moderate";
    if (score >= 10) grade = "excellent";
    else if (score >= 7) grade = "good";
    else if (score >= 4) grade = "moderate";
    else grade = "caution";

    return {
      id: def.id,
      name: def.name,
      nameCn: def.nameCn,
      category: def.category,
      description: def.desc,
      score,
      grade,
      reading: def.meanings[grade],
      advice: def.advice,
    };
  });

  const sorted = [...houses].sort((a, b) => b.score - a.score);
  const highestHouse = sorted[0];
  const lowestHouse = sorted[sorted.length - 1];
  const averageScore = Number(
    (houses.reduce((acc, h) => acc + h.score, 0) / houses.length).toFixed(1),
  );

  let overallSummary = "";
  if (averageScore >= 8.5) {
    overallSummary =
      "ดวงชะตาโดยรวมอยู่ในเกณฑ์ 'มหาศุภมงคล' มีพลังบุญหนุนนำสูง โดดเด่นทั้งวาสนาและทรัพย์สิน หากตั้งใจมุ่งมั่นจะสร้างตัวได้อย่างมั่นคงและรวดเร็ว";
  } else if (averageScore >= 6.5) {
    overallSummary =
      "ดวงชะตาโดยรวมอยู่ในเกณฑ์ 'เจริญก้าวหน้ามั่นคง' ชีวิตราบรื่น มีจุดแข็งที่ชัดเจน พึ่งพาตนเองได้ดีและมีผู้ใหญ่คอยอุปถัมภ์";
  } else {
    overallSummary =
      "ดวงชะตาต้องอาศัย 'ความเพียรและสติ' เป็นเข็มทิศนำทาง แม้จะมีบททดสอบหลายช่วง แต่หากมีสติ รอบคอบ และหมั่นทำบุญ จะพลิกชะตาให้รุ่งโรจน์ได้อย่างน่าทึ่ง";
  }

  // คำนวณช่วงวัยทอง (Golden Ages) ตามรอบเรือน
  const goldenAges = [
    {
      ageRange: "อายุ 1 - 12 ปี",
      houseName: houses[0].name,
      highlight: `อิทธิพลเรือน${houses[0].name} (${houses[0].score} คะแนน): ${houses[0].reading}`,
    },
    {
      ageRange: "อายุ 13 - 24 ปี",
      houseName: houses[2].name,
      highlight: `อิทธิพลเรือน${houses[2].name} (${houses[2].score} คะแนน): ${houses[2].reading}`,
    },
    {
      ageRange: "อายุ 25 - 36 ปี",
      houseName: houses[9].name,
      highlight: `อิทธิพลเรือน${houses[9].name} (${houses[9].score} คะแนน): ${houses[9].reading}`,
    },
    {
      ageRange: "อายุ 37 - 48 ปี",
      houseName: houses[1].name,
      highlight: `อิทธิพลเรือน${houses[1].name} (${houses[1].score} คะแนน): ${houses[1].reading}`,
    },
    {
      ageRange: "อายุ 49 - 60 ปี",
      houseName: houses[10].name,
      highlight: `อิทธิพลเรือน${houses[10].name} (${houses[10].score} คะแนน): ${houses[10].reading}`,
    },
    {
      ageRange: "อายุ 61 ปีขึ้นไป",
      houseName: houses[8].name,
      highlight: `อิทธิพลเรือน${houses[8].name} (${houses[8].score} คะแนน): ${houses[8].reading}`,
    },
  ];

  return {
    birthDate: birthDateStr,
    dayName: THAI_DAYS[dayIndex],
    zodiacYearName: ZODIAC_YEARS[zodiacIndex],
    houses,
    highestHouse,
    lowestHouse,
    averageScore,
    overallSummary,
    goldenAges,
  };
}
